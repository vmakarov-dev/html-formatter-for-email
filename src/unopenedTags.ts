// Диагностика "неоткрытых" тегов (см. UnopenedTagInfo/checkUnopenedChild
// в formatter.ts) — зеркальная пара к незакрытым тегам. У ряда тегов
// есть узкий, точно известный набор осмысленных родителей — если
// РЕАЛЬНЫЙ родитель тега в дереве не входит в этот набор, значит между
// ними пропущен промежуточный тег (например, вырезали <table>, и <tr>
// оказался прямым ребёнком чего-то постороннего).
//
// Список НАМЕРЕННО ограничен только тегами, у которых набор валидных
// родителей известен заранее и достаточно узкий, чтобы предположение о
// ПРОПУЩЕННОМ теге было однозначным (в отличие от, например, <li>,
// которому подойдёт и <ul>, и <ol>, и <menu>, — гадать, какой из них
// имелся в виду, не станем). Первый элемент списка — тот тег, который
// будет ПРЕДЛОЖЕН для вставки (самый вероятный/частый вариант).
export const REQUIRED_PARENT: Record<string, string[]> = {
  td: ["tr"],
  th: ["tr"],
  dt: ["dl"],
  dd: ["dl"],
  // table — самый частый вариант и то, что стоит предлагать; tbody/thead/
  // tfoot тоже валидны как прямой родитель tr, поэтому включены в набор
  // ДОПУСТИМЫХ, чтобы не путать их с настоящим багом.
  tr: ["table", "tbody", "thead", "tfoot"],
};
